# MarqueeLight

Android 跑马灯边缘通知应用，能够在系统通知到来时触发屏幕边缘动画。支持：

- 自定义颜色
- 自定义流速
- 通知类型区分颜色
- 通知触发后持续 3 秒
- 后台运行
- 省电模式

## 结构

- `app/` - Android 应用核心代码
- `build.gradle` - 根构建脚本
- `settings.gradle` - 项目配置

## 运行方式

1. 打开 Android Studio
2. 导入该项目
3. 选择一个 Android 设备或模拟器
4. 运行应用

## 使用说明

- 在 App 中开启跑马灯功能
- 授予通知访问权限
- 使用系统通知（短信、通话、应用通知）触发动画

## 注意事项

- 这是一个基础版本，后续可扩展为更完整的 UI 配置界面
- 实际系统通知监听需要用户在系统设置中开启“通知访问权限”
- 后台运行需根据 Android 版本和系统限制做兼容

